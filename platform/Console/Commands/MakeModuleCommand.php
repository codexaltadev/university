<?php

namespace Platform\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Str;

/**
 * php artisan module:make-uwms {Name} [--slug=] (FR-MODM-15, Module Guide §3).
 * Creates the standard module skeleton: manifest with uwms block, Extension,
 * service provider, Filament plugin, seeder, translations and README.
 */
class MakeModuleCommand extends Command
{
    protected $signature = 'module:make-uwms {name : PascalCase module name, e.g. FacultyMember}
                            {--slug= : Module slug (default: kebab-case of the name)}
                            {--type=installable : core or installable}';

    protected $description = 'Create a new platform module skeleton';

    public function handle(): int
    {
        $name = Str::studly($this->argument('name'));
        $slug = $this->option('slug') ?: Str::kebab($name);
        $type = $this->option('type');

        if (! preg_match('/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/', $slug)) {
            $this->error('Slug must be lowercase letters, digits and "-".');

            return self::FAILURE;
        }

        $path = base_path("Modules/{$name}");

        if (File::exists($path)) {
            $this->error("Modules/{$name} already exists.");

            return self::FAILURE;
        }

        $vars = [
            '{{Name}}' => $name,
            '{{slug}}' => $slug,
            '{{prefix}}' => Str::replace('-', '_', $slug).'_',
            '{{lower}}' => Str::lower($name),
            '{{type}}' => $type,
            '{{core}}' => config('platform.version'),
            '{{coreMajor}}' => Str::before(config('platform.version'), '.'),
            '{{title}}' => Str::headline($name),
        ];

        foreach ($this->files() as $file => $content) {
            $target = $path.'/'.strtr($file, $vars);
            File::ensureDirectoryExists(dirname($target));
            File::put($target, strtr($content, $vars));
        }

        $this->components->info("Module {$name} created in Modules/{$name}.");
        $this->line('  Next: add a model and migration, then');
        $this->line("  php artisan uwms:module:install Modules/{$name} && php artisan uwms:module:activate {$slug}");

        return self::SUCCESS;
    }

    /** @return array<string, string> relative path => content */
    protected function files(): array
    {
        return [
            'module.json' => <<<'JSON'
            {
                "name": "{{Name}}",
                "alias": "{{lower}}",
                "description": "",
                "keywords": [],
                "priority": 50,
                "providers": ["Modules\\{{Name}}\\Providers\\{{Name}}ServiceProvider"],
                "files": [],
                "uwms": {
                    "slug": "{{slug}}",
                    "version": "1.0.0",
                    "type": "{{type}}",
                    "requires_core": "^{{coreMajor}}.0",
                    "default_active": true,
                    "author": { "name": "DIU Web Team", "email": "web@example.edu" },
                    "license": "proprietary",
                    "table_prefix": "{{prefix}}",
                    "dependencies": {},
                    "optional_dependencies": [],
                    "morph_aliases": {},
                    "custom_permissions": [],
                    "provides": {}
                }
            }

            JSON,
            'composer.json' => <<<'JSON'
            {
                "name": "uwms/{{slug}}",
                "description": "{{title}} module",
                "authors": [{ "name": "DIU Web Team", "email": "web@example.edu" }],
                "require": {},
                "autoload": {
                    "psr-4": {
                        "Modules\\{{Name}}\\": "app/",
                        "Modules\\{{Name}}\\Database\\Factories\\": "database/factories/",
                        "Modules\\{{Name}}\\Database\\Seeders\\": "database/seeders/"
                    }
                },
                "autoload-dev": {
                    "psr-4": { "Modules\\{{Name}}\\Tests\\": "tests/" }
                }
            }

            JSON,
            'README.md' => <<<'MD'
            # {{title}}

            What this module does.

            | | |
            |---|---|
            | Slug | `{{slug}}` |
            | Tables | `{{prefix}}*` |
            | Permissions | Generated by Shield from the resources; custom: none |
            | Settings | none |

            ## Views

            View names, the variables each receives, and Livewire `wire:` properties / actions
            (theme override contract — Theme Guide §9–10).

            MD,
            'CHANGELOG.md' => "# Changelog\n\n## 1.0.0\n\n- First version.\n",
            'app/{{Name}}Extension.php' => <<<'PHP'
            <?php

            namespace Modules\{{Name}};

            use Modules\{{Name}}\Filament\{{Name}}Plugin;
            use Platform\Contracts\ModuleExtension;
            use Platform\Registry\Registrar;

            /**
             * Everything this module adds to the platform (SAD Part A §7).
             * Each registration needs the matching key in module.json "provides".
             */
            final class {{Name}}Extension implements ModuleExtension
            {
                public function register(Registrar $r): void
                {
                    $r->filamentPlugin({{Name}}Plugin::class);
                }
            }

            PHP,
            'app/Providers/{{Name}}ServiceProvider.php' => <<<'PHP'
            <?php

            namespace Modules\{{Name}}\Providers;

            use Nwidart\Modules\Support\ModuleServiceProvider;

            class {{Name}}ServiceProvider extends ModuleServiceProvider
            {
                protected string $name = '{{Name}}';

                protected string $nameLower = '{{lower}}';
            }

            PHP,
            'app/Filament/{{Name}}Plugin.php' => <<<'PHP'
            <?php

            namespace Modules\{{Name}}\Filament;

            use Filament\Contracts\Plugin;
            use Filament\Panel;

            class {{Name}}Plugin implements Plugin
            {
                public static function make(): static
                {
                    return app(static::class);
                }

                public function getId(): string
                {
                    return '{{slug}}';
                }

                public function register(Panel $panel): void
                {
                    $panel->resources([
                        // Resources\{Plural}\{Model}Resource::class,
                    ]);
                }

                public function boot(Panel $panel): void {}
            }

            PHP,
            'database/seeders/{{Name}}DatabaseSeeder.php' => <<<'PHP'
            <?php

            namespace Modules\{{Name}}\Database\Seeders;

            use Illuminate\Database\Seeder;

            /** Required default data only, no demo content; must be safe to run twice. */
            class {{Name}}DatabaseSeeder extends Seeder
            {
                public function run(): void
                {
                    //
                }
            }

            PHP,
            'database/migrations/.gitkeep' => '',
            'database/factories/.gitkeep' => '',
            'config/config.php' => "<?php\n\nreturn [\n    'name' => '{{Name}}',\n];\n",
            'resources/views/.gitkeep' => '',
            'lang/en/{{lower}}.php' => "<?php\n\nreturn [\n    'title' => '{{title}}',\n];\n",
            'lang/bn/{{lower}}.php' => "<?php\n\nreturn [\n    'title' => '{{title}}',\n];\n",
            'routes/web.php' => "<?php\n\nuse Illuminate\\Support\\Facades\\Route;\n\n// Route names start with \"{{slug}}.\"\n",
            'tests/Feature/.gitkeep' => '',
        ];
    }
}
